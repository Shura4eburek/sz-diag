namespace SzDiag.Cli;

/// <summary>Подсказка про <c>--detach</c> для длинных синхронных <c>exec</c> — печатается ДО
/// старта, а не после потери данных (бэклог п.220).
///
/// Боль (СЗ 161190, 25.08.2026). 22-минутное наблюдение под FurMark запустили обычным
/// <c>exec</c> — синхронный режим копит вывод целиком и отдаёт его только в конце, показать
/// «промежуточно» нечего. Фоновую задачу на стороне хоста харнесс прибил на середине, и все
/// 30 минут наблюдения пропали (в файле только <c>[killed]</c>). Перезапускать пришлось через
/// <c>--detach</c>, где вывод пишется в файл на клиенте и переживает что угодно.</summary>
public static class ExecLongRunHint
{
    /// <summary>Таймаут, начиная с которого синхронный exec рискует потерять весь вывод
    /// целиком при любом сбое на пути хост↔hub↔агент.</summary>
    public const int ThresholdSeconds = 300;   // 5 минут

    public static bool ShouldWarn(int? timeoutSeconds, bool detach)
        => !detach && timeoutSeconds is { } t && t > ThresholdSeconds;
}

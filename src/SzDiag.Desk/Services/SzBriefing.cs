namespace SzDiag.Desk.Services;

/// <summary>Вводная сессии (`--append-system-prompt`): всё про СЗ живёт в Desk, ядро SzDiag.Claude
/// знает только ключ.</summary>
public static class SzBriefing
{
    /// <param name="szcli">Полный путь к szcli: на боксе он не в PATH, и без пути сессия тратит ход
    /// на «szcli is not recognized» (живая проверка части 2). null — «szcli» как есть.</param>
    public static string For(string sz, string? szcli)
    {
        var cli = szcli is null ? "szcli" : $"\"{szcli}\"";
        return $"""
            Ты ведёшь сервисную заявку (СЗ) {sz} в SzDiag Desk — окне оператора сервисного центра.
            Сессия привязана к одной СЗ: работай только с машиной {sz} (`{cli} … {sz}`), другие СЗ не трогай.
            szcli на этом боксе не в PATH — вызывай его полным путём: {cli}.
            Оператор читает ленту в окне Desk, а не терминал: отвечай кратко, по-русски, итог — в конце хода.
            Факты по ходу пиши в kb/СЗ/{sz}/ (діагностика.md, дії.md) — на украинском, как требует CLAUDE.md.
            Разрешения на инструменты оператор подтверждает кнопкой в окне; отказ не обходи другим способом.
            Соседние заявки: peers() — кто ещё в работе и чем его железо похоже на твоё; ask_peer(key, question) — выжимка kb соседа (даром), ask_peer(…, live: true) — вопрос его сессии (лимиты — в ответе инструмента). Сравнение «две одинаковые сборки» (как на 161432) — через ask_peer, а не через чужую машину.
            """;
    }
}

namespace SzDiag.Kb;

/// <summary>Шаблоны текстов, которые иначе собираются заново на каждой заявке.
///
/// Боль (бэклог п.84, СЗ 160306): ответ на жалобу писался вручную, и половину времени съели
/// не факты, а формат — текст трижды переделывали под то, как его реально используют.
/// Всё, что выяснилось тогда, зашито здесь, чтобы больше не выясняться:
/// адресат — колл-центр (не клиент), чистый plain text (сайт жалоб не держит разметку),
/// абзац одной строкой (иначе hard wrap вычищается бекспейсом при каждой вставке),
/// без инструкций КЦ и без оценочных деклараций, и ничего, что опровергается нашими же
/// журналами.</summary>
public static class KbTemplates
{
    /// <summary>Имя папки шаблонов в vault (украинский — как и весь контент базы знаний).</summary>
    public const string FolderName = "Шаблони";

    /// <summary>Имя файла шаблона ответа на жалобу.</summary>
    public const string ComplaintReplyFile = "відповідь-на-скаргу.md";

    /// <summary>Шаблон ответа для колл-центра. Внутри — plain text без разметки: он
    /// копируется на сайт жалоб как есть.</summary>
    public static string ComplaintReply { get; } =
        """
        # Шаблон: відповідь на скаргу (для КЦ)

        Як користуватися: скопіювати блок нижче, підставити факти з `діагностика.md` та `дії.md`,
        видалити зайві рядки. Формат навмисно простий — сайт скарг не тримає розмітки.

        Правила (перевірені на 160306, не прибирати):
        - адресат — колл-центр, а не клієнт: звертання «шановний клієнте» тут зайве;
        - тільки plain text: без **, #, таблиць та емодзі; розділи — рядком великими літерами;
        - абзац пишеться ОДНИМ рядком, без переносу по ширині (інакше при вставці його
          доводиться чистити вручну);
        - не інструктувати КЦ («що можна казати») — на живій відповіді це виявилось марним;
        - без оціночних декларацій («провини сервісу не встановлено») — лише факти й дії;
        - не писати того, що спростовується нашими ж журналами (напр. «дефект не відтворюється»,
          коли машина вимикалась на нашому стенді — див. `szcli reboots`).

        ---

        ЩО ЗРОБЛЕНО
        1. …
        2. …

        ЩО ВСТАНОВЛЕНО
        1. …
        2. …

        ПОЗИЦІЯ СЕРВІСУ
        …

        ДВА ВАРІАНТИ ДЛЯ КЛІЄНТА
        1. …
        2. …

        ЯКЩО КЛІЄНТ ТИСНЕ
        …
        """;
}
